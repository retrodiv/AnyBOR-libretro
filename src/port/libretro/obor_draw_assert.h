static inline void obor_draw_assert(int value, const char *expression,
                                    const char *function, const char *file, int line)
{
    unsigned site = 7;
    if(value) return;
    if(strcmp(function, "setDrawMethod") == 0) {
        if(strcmp(expression, "index >= 0") == 0) site = 0;
        else if(strcmp(expression, "a != NULL") == 0) site = 1;
        else if(strcmp(expression, "m != NULL") == 0) site = 2;
        else if(strcmp(expression, "index < a->numframes") == 0) site = 3;
    } else if(strcmp(function, "getDrawMethod") == 0) {
        if(strcmp(expression, "index >= 0") == 0) site = 4;
        else if(strcmp(expression, "a != NULL") == 0) site = 5;
        else if(strcmp(expression, "index < a->numframes") == 0) site = 6;
    }
    if(site < 7) {
        for(unsigned i = 0; i < sizeof(obor_draw_assert_locations) /
                                    sizeof(*obor_draw_assert_locations); ++i) {
            const obor_draw_assert_location *location = &obor_draw_assert_locations[i];
            if(location->engine == OBOR_ENGINE_BUILD && location->revision == obor_profile_build) {
                file = "openbor.c";
                line = (int)location->line[site];
                break;
            }
        }
    }
#if OBOR_ENGINE_BUILD >= 3811
    if(obor_profile_build >= 3811) {
        exitIfFalse(0, expression, function, file, line);
        return;
    }
#endif
#ifndef NDEBUG
    obor_port_assert(0, expression, function, file, line);
#else
    (void)expression;
    (void)function;
    (void)file;
    (void)line;
#endif
}
#ifdef NDEBUG
/* Disabled historical assertions do not evaluate their predicate. */
#define OBOR_DRAW_ASSERT(value) do { if(obor_profile_build >= 3811) \
    obor_draw_assert(!!(value), #value, __func__, __FILE__, __LINE__); } while(0)
#else
#define OBOR_DRAW_ASSERT(value) \
    obor_draw_assert(!!(value), #value, __func__, __FILE__, __LINE__)
#endif
#else
/* Header-only probes without an engine context keep their native assertion. */
#define OBOR_DRAW_ASSERT(value) assert(value)
#endif
#endif
