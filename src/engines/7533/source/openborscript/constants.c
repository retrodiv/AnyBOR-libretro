static LONG obor_profile_property_constant(const char *name, LONG value)
{
    if (strncmp(name, "AIMOVE1_", 8) == 0)
    {
        return (LONG)obor_aimove_to_script(value == AIMOVE1_NORMAL ? obor_normal_aimove() : (uint32_t)value);
    }
    if (strncmp(name, "SPAWN_TYPE_", 11) == 0)
    {
        return (LONG)obor_profile_spawn_type((e_spawn_type)value);
    }
    if (strncmp(name, "TYPE_", 5) == 0)
    {
        return (LONG)obor_type_mask_to_script(value == TYPE_NONE ? obor_profile_type_none() : value);
    }
    if (strncmp(name, "FACTION_GROUP_", 14) == 0)
    {
        return (LONG)obor_faction_mask_to_script(value);
    }
    if (strcmp(name, "MODEL_PROPERTY_FACTION") == 0)
    {
        return (LONG)obor_profile_model_faction_index();
    }
    if (strncmp(name, "PROJECTILE_PRIME_", sizeof("PROJECTILE_PRIME_") - 1) == 0)
    {
        return (LONG)obor_projectile_prime_to_script((uint32_t)value);
    }
    if (strncmp(name, "KILL_ENTITY_TRIGGER_", sizeof("KILL_ENTITY_TRIGGER_") - 1) == 0)
    {
        return obor_kill_trigger_to_script((e_kill_entity_trigger)value);
    }
    if (obor_profile_build < 7478u &&
        (strncmp(name, "SHADOW_CONFIG_GRAPHIC_", sizeof("SHADOW_CONFIG_GRAPHIC_") - 1) == 0 ||
         strcmp(name, "SHADOW_CONFIG_DEFAULT") == 0))
    {
        return value >> 1;
    }
    if (obor_profile_build < 7475u && strncmp(name, "ENTITY_PROPERTY_", 16) == 0 &&
        value > ENTITY_PROPERTY_SHADOW_CONFIG_FLAGS)
    {
        --value;
    }
    if(obor_profile_build < 7553)
    {
        if(strncmp(name, "ENTITY_PROPERTY_", 16) == 0 && value > ENTITY_PROPERTY_GUARD_POINTS)
        {
            --value;
        }
        else if(strncmp(name, "MODEL_PROPERTY_", 15) == 0 && value > MODEL_PROPERTY_GUARD_RATE)
        {
            value -= 2;
        }
    }
    if(obor_profile_build >= 7557 && strncmp(name, "GLOBAL_CONFIG_PROPERTY_", 23) == 0)
    {
        if(value == GLOBAL_CONFIG_PROPERTY_FLASH) value = 4;
        else if(value == GLOBAL_CONFIG_PROPERTY_SHOW_GO) value = 5;
    }
    if(obor_profile_build < 7563 && strncmp(name, "FLASH_PROPERTY_", 15) == 0
        && value == FLASH_PROPERTY_Z_SOURCE)
    {
        value = 2;
    }
    return value;
}


// ===== openborconstant =====
#define IICMPCONST(x) \
if(stricmp(#x, constname)==0) {\
	v.lVal = obor_profile_property_constant(#x, (LONG)x);\
}


#define ICMPCONST(x) \
else if(stricmp(#x, constname)==0) {\
	v.lVal = obor_profile_property_constant(#x, (LONG)x);\
}


#define ICMPCONST_SINCE(x, revision) \
else if(obor_profile_build >= revision && stricmp(#x, constname)==0) {\
    v.lVal = obor_profile_property_constant(#x, (LONG)x);\
}

#define ICMPCONST_RANGE(x, first, last) \
else if(obor_profile_build >= first && obor_profile_build < last && stricmp(#x, constname)==0) {\
    v.lVal = obor_profile_property_constant(#x, (LONG)x);\
}

#define ICMPCONST_PROFILE_NAME(old_name, new_name, first) \
else if(stricmp(obor_profile_build < first ? #old_name : #new_name, constname)==0) {\
    v.lVal = obor_profile_property_constant(#new_name, (LONG)new_name);\
}

#define ICMPCONST_ALIAS_RANGE(name, value, first, last) \
else if(obor_profile_build >= first && obor_profile_build < last && stricmp(#name, constname)==0) {\
    v.lVal = obor_profile_property_constant(#name, (LONG)value);\
}

#define ICMPCONST_PROFILE_VALUE(name, value, first) \
else if(obor_profile_build >= first && stricmp(#name, constname)==0) {\
    v.lVal = (LONG)(value);\
}

#define ICMPCONST_CHEAT_MASK(x) \
else if(stricmp(#x, constname) == 0) {\
    v.lVal = (LONG)obor_profile_cheat_mask(x);\
}

#define ICMPSCONSTA(x, y) \
else if(strnicmp(constname, #x, sizeof(#x)-1)==0 && constname[sizeof(#x)-1] >= '1' && constname[sizeof(#x)-1]<='9') \
{ \
	v.lVal = (LONG)(y[atoi(constname+(sizeof(#x)-1))-1]);\
}

#define ICMPSCONSTB(x, y) \
else if(strnicmp(constname, #x, sizeof(#x)-1)==0 && constname[sizeof(#x)-1] >= '1' && constname[sizeof(#x)-1]<='9') \
{ \
	v.lVal = (LONG)(y[atoi(constname+(sizeof(#x)-1))+STA_ATKS-1]);\
}

#define ICMPSCONSTC(x) \
else if(strnicmp(constname, #x, sizeof(#x)-1)==0 && constname[sizeof(#x)-1] >= '1' && constname[sizeof(#x)-1]<='9') \
{ \
	v.lVal = (LONG)(atoi(constname+(sizeof(#x)-1))+STA_ATKS-1);\
}

#define ICMPCONST_MOVE_FLAG(name, first) \
else if(obor_profile_build >= first && \
        stricmp(obor_profile_build < 7498u ? "MOVE_CONSTRAINT_" #name : "MOVE_CONFIG_" #name, constname)==0) {\
    v.lVal = (LONG)obor_move_flags_to_script(MOVE_CONFIG_ ## name);\
}

#define ICMPCONST_BEFORE(name, last) \
else if(obor_profile_build < last && stricmp(#name, constname)==0) {\
    v.lVal = obor_profile_property_constant(#name, (LONG)name);\
}

